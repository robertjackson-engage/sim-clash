def bn(u,v):
    x=0.2+1.75*u
    z=6.9-(4.7-0.9*(1-abs(2*u-1)))*v
    return (x, 0.16*sin(v*6.5+u*1.5)*v, z)
fs=k.sheet(bn,10,24,'#e8372c')
def cb(c,n):
    u=(c.x-0.2)/1.75; v=(6.9-c.z)/(4.7-0.9*(1-abs(2*u-1)))
    if u<0.1 or u>0.9 or v<0.06: return '#ffd21f'
    d=((u-0.5)*1.75)**2+((v-0.3)*4.2)**2
    if d<0.09: return '#e8372c'
    if d<0.34: return '#f4f4ee'
    if v>0.62: return ('#2f7fe8','#f4f4ee')[int((v-0.62)/0.095)%2]
    return None
k.tint(fs,cb)
k.poly([(-0.06,0,7.3),(-1.3,0.1,7.05),(-0.06,0,6.75)],'#2f7fe8')
